/**
 * Shape of the dictionary, with every leaf widened to `string`.
 *
 * `ka` is declared `as const` so its own literal values stay exact, but
 * `en.ts` must be free to supply different English strings for the same
 * keys — widening here is what makes `en: Dictionary` typecheck while still
 * failing the build if a key is missing or misspelled.
 */
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? readonly Widen<U>[]
    : { [K in keyof T]: Widen<T[K]> }

export type Dictionary = Widen<typeof ka>
